/* Regression tests for the pure production-readiness gate. Run with node scripts/blackfist-readiness-test.cjs */
const assert=require("node:assert/strict");
const fs=require("node:fs");
const vm=require("node:vm");
const ts=require("typescript");
const source=fs.readFileSync("src/lib/blackfist/readiness-summary.ts","utf8");
const js=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText;
const exports={};vm.runInNewContext(js,{exports});
const summarize=exports.buildReadinessSummary;
assert.equal(typeof summarize,"function");
const keys=["screenplay","storyboard","animation","voices","soundtrack","video","alignment","runtime","reviewMaster"];
const make=(blocked={})=>keys.map(key=>({key,title:key,issues:blocked[key]||[]}));
const ready=summarize(make());
assert.equal(ready.completedStages,9);
assert.equal(ready.totalStages,9);
assert.equal(ready.readyForReview,true);
assert.equal(ready.checklist.length,0);
assert.equal(ready.nextAction,null);
assert.equal(ready.milestones.every(m=>m.ready),true);
const blocked=summarize(make({screenplay:["Approve screenplay"],voices:["Lock actor voice"],video:["Approve sequence"]}));
assert.equal(blocked.completedStages,6);
assert.equal(blocked.readyForReview,false);
assert.equal(blocked.nextAction.stage,"screenplay");
assert.equal(blocked.checklist.length,3);
assert.equal(blocked.milestones.find(m=>m.key==="audio").ready,false);
assert.equal(blocked.milestones.find(m=>m.key==="assembly").ready,false);
assert.equal(blocked.milestones.find(m=>m.key==="editorial").ready,false);
const sequence=summarize(make({video:["Scene requires exactly one human-approved sequence"]}));
assert.equal(sequence.milestones.find(m=>m.key==="assembly").ready,false);
assert.equal(sequence.milestones.find(m=>m.key==="animation").ready,true);
const empty=summarize([]);
assert.equal(empty.readyForReview,false);
console.log("BlackFist readiness regression tests passed");
